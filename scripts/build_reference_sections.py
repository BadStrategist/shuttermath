def tbl(headers, rows, caption):
    h = "".join(f"<th>{c}</th>" for c in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return (f'<div class="tbl-scroll"><table class="aeo-tbl"><caption>{caption}</caption>'
            f"<thead><tr>{h}</tr></thead><tbody>{body}</tbody></table></div>")


def dof_section():
    d = T["dof"]
    a = [(f"f/{r['N']}", r["near"], r["far"], r["dof"], r["H"]) for r in d["byAperture"]]
    b = [(f"{r['f']} mm", r["near"], r["far"], r["dof"], r["H"]) for r in d["byFocal"]]
    c = [(r["s"], r["near"], r["far"], r["dof"]) for r in d["byDistance"]]
    return f"""
<section id="dof-tables">
<h2>Depth of field tables (full frame, sharpness circle 0.029 mm)</h2>
<div class="aeo-answer"><p><strong>Short answer:</strong> at 3 m with a 50 mm lens, f/8 gives a
depth of field of {d['byAperture'][5]['dof']} (sharp from {d['byAperture'][5]['near']} to {d['byAperture'][5]['far']}).
Opening up to f/1.4 shrinks that to {d['byAperture'][0]['dof']}; stopping down to f/16 grows it to {d['byAperture'][7]['dof']}.
Every figure below is computed with the same formula the calculator uses.</p></div>
{tbl(["Aperture (50 mm, 3 m)", "Near limit", "Far limit", "Total DoF", "Hyperfocal"], a, "Changing aperture while focal length and focus distance stay fixed")}
{tbl(["Focal length (f/8, 3 m)", "Near limit", "Far limit", "Total DoF", "Hyperfocal"], b, "Changing focal length at f/8 from the same 3 m focus distance")}
{tbl(["Focus distance (50 mm, f/2.8)", "Near limit", "Far limit", "Total DoF"], c, "Changing focus distance at 50 mm f/2.8")}
<h3>Why the numbers move the way they do</h3>
<p>Depth of field grows with the square of focus distance, so doubling the focus distance
roughly quadruples the sharp zone at the same aperture. It shrinks with the square of focal
length, which is why an 85 mm portrait lens at f/8 has less depth than a 24 mm wide angle at
the same f/8. Aperture acts linearly: one stop down adds about 41% more depth, not double.</p>
<p>The formulas behind the table are standard thin-lens equations. Hyperfocal distance is
<em>H = f² / (N × c) + f</em>, where <em>f</em> is focal length in mm, <em>N</em> the f-number and
<em>c</em> the circle of confusion. The near limit is <em>H × s / (H + (s − f))</em> and the far
limit is <em>H × s / (H − (s − f))</em>, with <em>s</em> the focus distance. Once <em>s</em> reaches
<em>H</em> the far limit becomes infinity, which is the hyperfocal trick: focus at H and
everything from H/2 to infinity is acceptably sharp.</p>
<p class="aeo-note">Circle of confusion here is the sensor diagonal divided by 1500, the
classic 35 mm standard (0.029 mm on full frame). A print viewed closer than the standard
0.25 m viewing distance needs a smaller circle: divide the CoC by the same factor you enlarge
the print.</p>
</section>"""


def hyper_m(f, N, c=0.029):
    return (f * f / (N * c) + f) / 1000.0


def fov_h(f):
    import math
    return math.degrees(2 * math.atan(35.9 / (2 * f)))


