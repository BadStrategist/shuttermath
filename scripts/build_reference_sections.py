def exposure_section():
    rows = []
    for name, ev in LIGHT:
        rows.append((name, str(ev),
                     "f/2.8 at " + fmt_t(snap_t((2.8 ** 2) / (2 ** ev))),
                     "f/8 at " + fmt_t(snap_t(64 / (2 ** ev)))))
    return (
        "<section><h2>Exposure value chart: what EV means in practice</h2>"
        '<div class="aeo-answer"><p><strong>Short answer:</strong> EV measures the light, not the camera settings. '
        "EV 15 is bright sun, EV 8 is a lit street at night, and each EV step is one stop of shutter, aperture or ISO. "
        "At ISO 100, EV = log2(N squared / t).</p></div>"
        + tbl(["Scene", "EV at ISO 100", "Start at f/2.8", "Start at f/8"], rows,
              "Starting exposures at ISO 100, rounded to real shutter speeds. Meter, then adjust for the subject.")
        + "<p>Read this as a sanity check. A grey card in bright sun sits at EV 15; snow and white sand need +1 to "
        "+2 EV of compensation because the meter wants to render them grey, and a dark forest or a backlit subject "
        "needs -1 EV.</p>"
        "<p>One EV is one stop, so equivalent exposures share an EV: f/2.8 at 1/500 s, f/8 at 1/60 s and f/11 at "
        "1/30 s are the same brightness. The calculator above converts between them without changing the exposure.</p>"
        "</section>"
    )


# --- print resolution -------------------------------------------------------
SIZES = [(4, 6), (5, 7), (6, 9), (8, 10), (8, 12), (11, 14), (16, 20), (20, 30), (24, 36)]


def mp(w, h, dpi):
    return (w * dpi / 1000) * (h * dpi / 1000)


def print_section():
    rows = []
    for w, h in SIZES:
        rows.append((f"{w} x {h} in",
                     f"{int(w * 300)} x {int(h * 300)}",
                     f"{mp(w, h, 300):.1f} MP",
                     f"{mp(w, h, 240):.1f} MP",
                     f"{mp(w, h, 150):.1f} MP"))
    return (
        "<section><h2>How many megapixels a print size needs</h2>"
        '<div class="aeo-answer"><p><strong>Short answer:</strong> multiply inches by dots per inch. An 8 x 10 in '
        "print at 300 dpi needs 2400 x 3000 pixels, which is 7.2 megapixels. At 150 dpi the same print needs only "
        "1.8 megapixels, and at normal viewing distance that is still sharp.</p></div>"
        + tbl(["Print size", "Pixels at 300 dpi", "300 dpi", "240 dpi", "150 dpi"], rows,
              "Pixels and megapixels required for each print size. Pixels are width x height.")
        + "<p>300 dpi is the print industry default for anything held in the hand. Wall prints are viewed from further "
        "away, so 240 dpi covers a 16 x 20 and 150 dpi is acceptable at 24 x 36 when the print hangs behind a sofa. "
        "What matters is pixels per degree of view, not a fixed number.</p>"
        "<p>Upscaling adds pixels, not detail. If the calculator says you are short by a factor of two, a sharper lens, "
        "a longer exposure on a tripod or a stitched panorama will do more than any resize algorithm.</p>"
        "</section>"
    )


# --- flash guide number -----------------------------------------------------
GNS = [30, 40, 50, 60]
FSTOPS = [2.8, 4, 5.6, 8]


def flash_section():
    rows = []
    for gn in GNS:
        rows.append((f"GN {gn} m", " | ".join(f"{gn / n:.1f} m" for n in FSTOPS)))
    rows = [(g, *v.split(" | ")) for g, v in rows]
    return (
        "<section><h2>Guide number chart: how far the flash reaches</h2>"
        '<div class="aeo-answer"><p><strong>Short answer:</strong> distance = guide number divided by f-number. '
        "A flash with GN 60 m at ISO 100 reaches 7.5 m at f/8 and 21.4 m at f/2.8. Double the ISO and the guide "
        "number rises by 1.4 times.</p></div>"
        + tbl(["Flash", "f/2.8", "f/4", "f/5.6", "f/8"], rows,
              "Maximum distance in metres at ISO 100 for common guide numbers.")
        + "<p>Guide numbers are quoted at ISO 100 and a specific zoom position, usually the widest the head covers. "
        "Zooming the head concentrates the light and raises the effective guide number; a diffuser spreads it and "
        "cuts it by roughly a stop. Bounce flash loses two to three stops because the ceiling is a poor reflector.</p>"
        "<p>At ISO 400 the guide number doubles, so the same flash reaches twice as far at the same aperture. That is "
        "why high ISO plus a small aperture is the usual way to light a large room from one speedlight.</p>"
        "</section>"
    )


# --- ND filter --------------------------------------------------------------
ND = [(1, "ND2"), (2, "ND4"), (3, "ND8"), (4, "ND16"), (5, "ND32"), (6, "ND64"),
      (7, "ND128"), (8, "ND256"), (9, "ND512"), (10, "ND1000"), (13, "ND8000"), (15, "ND32000")]


def nd_section():
    rows = []
    for stops, name in ND:
        factor = 2 ** stops
        rows.append((f"{stops} stop" if stops == 1 else f"{stops} stops", f"{name}", f"{factor}x", fmt_t(factor), fmt_t(factor / 15)))
    return (
        "<section><h2>ND filter chart: stops to shutter speed</h2>"
        '<div class="aeo-answer"><p><strong>Short answer:</strong> each stop doubles the exposure time. A 10 stop '
        "filter multiplies a 1/15 s exposure by 1024, which is 68 seconds. A 3 stop filter turns 1/60 s into 1/8 s.</p></div>"
        + tbl(["Strength", "Filter name", "Light factor", "1 s becomes", "1/15 s becomes"], rows,
              "Exposure multiplication for each ND strength. The name is the transmission, so ND1000 passes 1/1000 of the light.")
        + "<p>Filter names and stops are often confused. ND8 is 3 stops, not 8. ND1000 is 10 stops, and some makers "
        "label it ND3.0 or 10 stop. The number after ND is the transmission factor, and stops = log2(factor).</p>"
        "<p>Stacking filters adds stops: a 6 stop and a 3 stop together give 9 stops, a factor of 512. Add the stops, "
        "never the filter names. Vignetting and colour cast grow with the stack, so prefer one strong filter.</p>"
        "</section>"
    )


