def angle_section():
    rows = T["ang"]["rows"]

    def as_frac(txt):
        if txt.endswith(" ms"):
            v = float(txt.split()[0]) / 1000.0
            return f"1/{round(1 / v)} s"
        return txt

    body = [(f"{r['fps']} fps", as_frac(r["a360"]), as_frac(r["a180"]), as_frac(r["a90"]), as_frac(r["a45"])) for r in rows]
    return f"""
<section id="shutter-angle-table">
<h2>Shutter speed by frame rate and shutter angle</h2>
<div class="aeo-answer"><p><strong>Short answer:</strong> the 180° shutter rule sets exposure
time to half the frame interval, so 24 fps gives 1/48 s, 30 fps gives 1/60 s and 60 fps gives
1/120 s. Multiply the frame rate by 360 and divide by the shutter angle to get the exact
speed: 24 × 360 / 180 = 48.</p></div>
{tbl(["Frame rate", "360°", "180°", "90°", "45°"], body, "Exact shutter speed. Cameras display the nearest standard value, so 23.976 fps at 180° shows 1/48.")}
<h3>Why 180° is the default</h3>
<p>A 180° shutter gives motion blur that matches how the eye reads movement at 24 fps. Narrow
the angle (90°, 45°) and you get crisper frames that survive slow motion and look like Saving
Private Ryan; open it to 360° and motion smears, which suits dream sequences and low light.</p>
<p>Frame rate and shutter angle together decide whether lights flicker. At 50 Hz mains, shoot
25 or 50 fps; at 60 Hz, shoot 30 or 60 fps. On mixed or unknown lighting, a narrow angle lets
you keep 24 fps without banding.</p>
</section>"""



# --- shared helpers ---------------------------------------------------------
STD_T = [1/8000, 1/4000, 1/2000, 1/1000, 1/500, 1/250, 1/125, 1/60, 1/30, 1/15, 1/8,
         1/4, 1/2, 1, 2, 4, 8, 15, 30, 60]


def snap_t(t):
    """Nearest real shutter speed, because nobody can dial 1/8359."""
    return min(STD_T, key=lambda x: abs(math.log(x) - math.log(t)))


def fmt_t(t):
    if t >= 60:
        return f"{t / 60:.0f} min"
    if t >= 1.05:
        return f"{t:.0f} s"
    if t >= 0.3:
        return f"{t:.1f} s"
    return "1/" + str(int(round(1 / t)))


